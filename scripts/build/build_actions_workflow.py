#!/usr/bin/env python3
"""Generate the copy-paste GitHub Actions workflow (.github/workflows/prqa.yml) from the canonical client.

    python3 scripts/build/build_actions_workflow.py          # (re)write .github/workflows/prqa.yml
    python3 scripts/build/build_actions_workflow.py --check  # exit 1 when the file on disk differs (used by the tests)

The workflow is self-contained: it embeds scripts/clients/prqa_actions_client.py verbatim in a quoted heredoc so a target
repository needs nothing but this one file plus two secrets. Keeping the client in its own file makes it unit-testable.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLIENT = ROOT / "scripts" / "clients" / "prqa_actions_client.py"
OUT = ROOT / ".github" / "workflows" / "prqa.yml"
HEREDOC = "PRQA_CLIENT"
INDENT = " " * 10

TEMPLATE = """# PRQA · PR QA Pilot — request an API-level QA run for a pull request from ANY repository.
#
# Copy this file unchanged to .github/workflows/prqa.yml, then configure in the target repository
# (Settings → Secrets and variables → Actions). Full guide: docs/GITHUB_ACTIONS_ONBOARDING.md in the PRQA repository.
#
#   Secrets (required)
#     PRQA_WEBHOOK_URL      public HTTPS URL of the PRQA receiver, e.g. https://prqa.example.org/webhook/prqa/actions
#     PRQA_WEBHOOK_SECRET   the SAME value as PRQA_WEBHOOK_SECRET in the PRQA worker environment (compose/.env)
#   Variables (optional)
#     PRQA_TRIGGER_LABEL    opt-in label that starts a run when added to a PR (default: "to be test")
#     PRQA_TEST_LEVEL       smoke | standard | comprehensive | security (default: standard)
#     PRQA_HTTP_TIMEOUT_SECONDS  per-request HTTP timeout (default 30, max 120)
#
# How it works: no checkout, no PR code is executed. The job resolves the PR through the GitHub API, builds a signed
# request (HMAC-SHA256 over "<timestamp>.<body>", idempotency key repo#pr@sha:level) and POSTs it to PRQA with a bounded
# timeout and at most 3 attempts. HTTP 202 = accepted. The validated QA result is reported to Discord by PRQA once the
# job and the result validation have completed — a green job here never means the PR passed.
#
# Generated by scripts/build/build_actions_workflow.py (PRQA repository). The embedded client is scripts/clients/prqa_actions_client.py.
name: PRQA · PR QA Pilot

on:
  workflow_dispatch:
    inputs:
      pr_number:
        description: Pull request number to test (must belong to this repository)
        required: true
        type: string
      test_level:
        description: PRQA test level
        required: false
        default: standard
        type: choice
        options:
          - smoke
          - standard
          - comprehensive
          - security
      force_rerun:
        description: Request a new run even if this head SHA was already submitted
        required: false
        default: false
        type: boolean
  pull_request:
    types: [labeled]

# Least privilege: metadata only. PRQA posts the optional PR comment with its own token, so no write scope is needed here.
permissions:
  contents: read
  pull-requests: read

# One request at a time per PR: an overlapping label + manual trigger is serialised, and the second one
# becomes a harmless "duplicate" on the PRQA side (same idempotency key).
concurrency:
  group: prqa-${{ github.repository }}-${{ github.event.pull_request.number || inputs.pr_number }}
  cancel-in-progress: false

jobs:
  request-qa:
    name: Request PRQA test
    if: >-
      github.event_name == 'workflow_dispatch' ||
      (github.event_name == 'pull_request' && github.event.label.name == (vars.PRQA_TRIGGER_LABEL || 'to be test'))
    runs-on: ubuntu-latest
    timeout-minutes: 10
    steps:
      - name: Guard — fork pull requests cannot be requested from the label trigger
        id: guard
        if: github.event_name == 'pull_request' && github.event.pull_request.head.repo.fork == true
        run: |
          echo "::notice::PRQA: pull request #${{ github.event.pull_request.number }} comes from a fork. Repository secrets are not available to fork PRs, so no request was sent. A maintainer can use 'Run workflow' (workflow_dispatch) instead; PRQA still applies its own fork policy."
          echo "skip=true" >> "$GITHUB_OUTPUT"

      - name: Request a PRQA test run (signed webhook call, no checkout)
        if: steps.guard.outputs.skip != 'true'
        env:
          PRQA_WEBHOOK_URL: ${{ secrets.PRQA_WEBHOOK_URL || vars.PRQA_WEBHOOK_URL }}
          PRQA_WEBHOOK_SECRET: ${{ secrets.PRQA_WEBHOOK_SECRET }}
          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
          PRQA_PR_NUMBER: ${{ github.event.pull_request.number || inputs.pr_number }}
          PRQA_TEST_LEVEL: ${{ inputs.test_level || vars.PRQA_TEST_LEVEL || 'standard' }}
          PRQA_TRIGGER_LABEL: ${{ vars.PRQA_TRIGGER_LABEL || 'to be test' }}
          PRQA_FORCE_RERUN: ${{ inputs.force_rerun || 'false' }}
          PRQA_HTTP_TIMEOUT_SECONDS: ${{ vars.PRQA_HTTP_TIMEOUT_SECONDS || '30' }}
          PRQA_EXPECTED_HEAD_SHA: ${{ github.event.pull_request.head.sha || '' }}
        run: |
          python3 - <<'__HEREDOC__'
__CLIENT__
          __HEREDOC__
"""


def render() -> str:
    client = CLIENT.read_text(encoding="utf-8").rstrip("\n")
    if HEREDOC in client:
        raise SystemExit(f"client must not contain the heredoc delimiter {HEREDOC}")
    body = "\n".join((INDENT + line) if line.strip() else "" for line in client.splitlines())
    return TEMPLATE.replace("__HEREDOC__", HEREDOC).replace("__CLIENT__", body)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 scripts/build/build_actions_workflow.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines, client {len(CLIENT.read_text().splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

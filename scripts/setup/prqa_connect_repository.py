#!/usr/bin/env python3
"""Connect ONE GitHub repository to PRQA's `to be test` trigger and generate its installation package.

    python3 scripts/setup/prqa_connect_repository.py connect OWNER/REPO [--webhook-url URL] [--local-test]
                                                     [--rotate-secret] [--register-repository] [--out DIR]
    python3 scripts/setup/prqa_connect_repository.py export-secret OWNER/REPO | gh secret set PRQA_WEBHOOK_SECRET --repo OWNER/REPO
    python3 scripts/setup/prqa_connect_repository.py revoke OWNER/REPO
    python3 scripts/setup/prqa_connect_repository.py status OWNER/REPO

`connect` creates (or reuses) the repository's connection — a non-secret id plus a 256-bit CSPRNG signing secret — in the
protected registry outside the project drive (default ~/.config/prqa/actions-connections, dir 750 / file 640), records
PRQA_ACTIONS_CONNECTIONS_DIR and PRQA_ACTIONS_CONNECTIONS_GID in ~/.config/prqa/secrets.env for compose, validates the
public HTTPS ingress URL, and writes a package WITHOUT any secret:

    <out>/<owner>__<repo>/.github/workflows/prqa-to-be-test.yml   the workflow to commit in the target repository
    <out>/<owner>__<repo>/INSTALL.md                              installation, verification and rollback guide
    <out>/<owner>__<repo>/connection.json                         non-secret metadata (id, repository, endpoint status)

The secret leaves the registry only through `export-secret`, which refuses to write to a terminal (pipe it straight into
`gh secret set`). Nothing here contacts GitHub, opens a tunnel, changes networking, pushes code or activates n8n.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "worker"))

from prqa_worker import actions_connections as conns  # noqa: E402

CLIENT = ROOT / "scripts" / "clients" / "prqa_to_be_test_client.py"
DEFAULT_CONNECTIONS_DIR = Path("~/.config/prqa/actions-connections")
DEFAULT_SECRETS_ENV = Path("~/.config/prqa/secrets.env")
DEFAULT_OUT = ROOT / "runs" / "repo-connection-packages"
REGISTRY_FILE = ROOT / "config" / "repositories.yaml"
WORKFLOW_PATH = ".github/workflows/prqa-to-be-test.yml"
HEREDOC = "PRQA_CLIENT"
INDENT = " " * 10

WORKFLOW_TEMPLATE = """# PRQA · `to be test` dispatch for __REPO__
#
# Generated by scripts/setup/prqa_connect_repository.py (PRQA repository) for connection __CID__. Do not edit by hand:
# regenerate instead. Install guide: INSTALL.md next to this file in the generated package.
#
#   Repository secrets (SECRET — never commit them, never paste them into this file)
#     PRQA_WEBHOOK_URL      public HTTPS URL of the PRQA ingress, ending in /webhook/prqa/actions
#     PRQA_WEBHOOK_SECRET   this repository's connection secret (scripts/setup/prqa_connect_repository.py export-secret)
#   Repository variable (not secret)
#     PRQA_CONNECTION_ID    __CID__
#
# Event policy: a run is dispatched when the exact, case-sensitive label "to be test" is added to an open, non-draft PR,
# or when a PR that carries it is opened, reopened, receives a new commit (synchronize) or is marked ready for review.
# Removing the label, any other label and every other action dispatch nothing. Fork PRs are skipped (no secrets).
#
# Security: `pull_request` (not pull_request_target), no checkout, no PR code, no GitHub token (permissions: {}), no
# third-party actions, no ${{ }} expressions inside the script: the client reads the event JSON from GITHUB_EVENT_PATH,
# signs "<timestamp>.<body>" with HMAC-SHA256 and POSTs ids/SHAs/refs only. A green job means "dispatched", never "passed".
name: PRQA · to be test

on:
  pull_request:
    types: [opened, reopened, labeled, synchronize, ready_for_review]

permissions: {}

concurrency:
  group: prqa-to-be-test-${{ github.event.pull_request.number }}
  cancel-in-progress: false

jobs:
  dispatch:
    name: Dispatch PRQA review
    # Coarse pre-filter only (GitHub expression comparisons ignore case); the exact label rule runs in the client.
    if: >-
      github.repository == '__REPO__' &&
      (github.event.action != 'labeled' || github.event.label.name == 'to be test')
    runs-on: ubuntu-latest
    timeout-minutes: 5
    steps:
      - name: Dispatch to PRQA (signed webhook, no checkout)
        env:
          PRQA_WEBHOOK_URL: ${{ secrets.PRQA_WEBHOOK_URL }}
          PRQA_WEBHOOK_SECRET: ${{ secrets.PRQA_WEBHOOK_SECRET }}
          PRQA_CONNECTION_ID: ${{ vars.PRQA_CONNECTION_ID }}
          PRQA_EXPECTED_REPOSITORY: __REPO__
          PRQA_HTTP_TIMEOUT_SECONDS: "20"
          PRQA_MAX_ATTEMPTS: "3"
        run: |
          python3 -I - <<'__HEREDOC__'
__CLIENT__
          __HEREDOC__
"""


class SetupError(Exception):
    pass


def render_workflow(repository: str, connection_id: str) -> str:
    if not conns.REPO_RE.match(repository) or not conns.CONNECTION_ID_RE.match(connection_id):
        raise SetupError("repository or connection id is malformed")
    client = CLIENT.read_text(encoding="utf-8").rstrip("\n")
    if HEREDOC in client:
        raise SetupError(f"client must not contain the heredoc delimiter {HEREDOC}")
    body = "\n".join((INDENT + line) if line.strip() else "" for line in client.splitlines())
    return (WORKFLOW_TEMPLATE.replace("__HEREDOC__", HEREDOC).replace("__CLIENT__", body)
            .replace("__REPO__", repository).replace("__CID__", connection_id))


def endpoint_status(url: str | None, local_test: bool) -> dict:
    if not url:
        return {"status": "unconfigured", "host": None,
                "detail": "no public HTTPS ingress is configured; the workflow fails visibly until PRQA_WEBHOOK_URL is set"}
    ok, reason = conns.validate_ingress_url(url, local_test=local_test)
    if not ok:
        raise SetupError(f"webhook URL rejected: {reason}")
    host = re.match(r"^https?://([^/:]+)", url.strip()).group(1)
    return {"status": "local_test" if url.startswith("http://") else "configured", "host": host, "detail": reason}


def render_install(repository: str, connection_id: str, endpoint: dict, registered: str) -> str:
    owner_repo = repository
    ep_line = {"unconfigured": "**UNCONFIGURED** — no public HTTPS endpoint was given. The workflow fails visibly "
                               "(\"PRQA is not configured\") until `PRQA_WEBHOOK_URL` is set. Nothing is dispatched.",
               "local_test": "**LOCAL TEST ONLY** — an http://127.0.0.1 endpoint, unreachable from GitHub-hosted runners.",
               "configured": f"configured: host `{endpoint.get('host')}` (reachability is not verified offline)."}[endpoint["status"]]
    return f"""# PRQA `to be test` — installation package for `{owner_repo}`

Connection id: `{connection_id}` (not secret) · Endpoint: {ep_line}
Registry entry: {registered}

## What is secret and what is not

| Name | Where | Secret? | Value |
|---|---|---|---|
| `PRQA_WEBHOOK_SECRET` | GitHub → Settings → Secrets and variables → Actions → **Secrets** | **SECRET** | exported by `export-secret` (never shown, never in this package) |
| `PRQA_WEBHOOK_URL` | GitHub → Actions → **Secrets** | **SECRET** (keeps the ingress host out of logs) | the public HTTPS ingress URL ending in `/webhook/prqa/actions` |
| `PRQA_CONNECTION_ID` | GitHub → Actions → **Variables** | not secret | `{connection_id}` |
| `{WORKFLOW_PATH}` | the repository (commit it) | not secret | the file in this package |

**Never commit the secret**, never paste it into the workflow, an issue, a PR, a chat or a log. The workflow file contains
no secret, no URL and no token.

## 1. Server provisioning (PRQA host, once)

1. The connection is already stored in the protected registry (`~/.config/prqa/actions-connections/connections.json`,
   directory 750, file 640, outside the project drive). `PRQA_ACTIONS_CONNECTIONS_DIR` and `PRQA_ACTIONS_CONNECTIONS_GID`
   were recorded in `~/.config/prqa/secrets.env`.
2. Recreate the worker so compose mounts the registry read-only at `/run/prqa-connections`
   (`scripts/start.sh` or `docker compose ... up -d prqa-worker`). Later connections are picked up without a restart.
3. Register the repository in `config/repositories.yaml` (`--register-repository` adds a **disabled,
   pending_approval** entry). Running real PRs additionally needs Phase-2 approval: `AUTOMATION_MODE=live`, the entry
   enabled + approved, and a fine-grained **read-only** `GITHUB_TOKEN` (Contents: read, Pull requests: read, Metadata:
   read) for PR context. Without that credential real dispatches fail closed with `503 GITHUB_READ_CREDENTIAL_MISSING`.
   While `AUTOMATION_MODE=review_only` every real dispatch is answered `200 blocked / REVIEW_ONLY_MODE` and nothing runs.
4. Public reachability is an operator decision: expose **only** `POST /webhook/prqa/actions` through an HTTPS reverse
   proxy. Never expose the n8n editor/REST API, the worker port, the model-proxy admin socket or the Docker socket.
   This tool never creates a tunnel and never changes network isolation.
5. The n8n receiver workflow (PRQA 01) must be active for the public path to work. Activation is a separate, explicit
   Phase-2 step; the generated package does not activate anything.

## 2. Repository installation (GitHub, maintainer with admin rights)

```bash
# secret: piped, never displayed, never in shell history
python3 scripts/setup/prqa_connect_repository.py export-secret {owner_repo} | gh secret set PRQA_WEBHOOK_SECRET --repo {owner_repo}
# secret: type it at the prompt (gh reads stdin) — the URL is kept secret too
gh secret set PRQA_WEBHOOK_URL --repo {owner_repo}
# variable (not secret)
gh variable set PRQA_CONNECTION_ID --repo {owner_repo} --body {connection_id}
```

Then commit `{WORKFLOW_PATH}` from this package to the default branch (through a normal reviewed PR) and create the
label `to be test` (exact spelling, case-sensitive).

## 3. Event policy

| Event | Result |
|---|---|
| PR opened already carrying `to be test` | dispatch |
| label `to be test` added | dispatch (exact, case-sensitive: `To Be Test` does nothing) |
| PR reopened while labelled | dispatch |
| new commit (`synchronize`) while labelled | dispatch (new head SHA = new run; same SHA = duplicate) |
| `ready_for_review` while labelled | dispatch |
| draft PR | nothing (dispatches when marked ready) |
| label removed | nothing new; already-dispatched work is not re-triggered |
| any other label / action | nothing |
| fork PR | nothing (no secrets for forks) |

## 4. Permissions and security

* `on: pull_request` (never `pull_request_target`), `permissions: {{}}` — the job has no GitHub token scope.
* No checkout, no PR code, no third-party action, no `${{{{ }}}}` inside the script; the event is read from
  `GITHUB_EVENT_PATH` as JSON. Timeout 5 minutes, at most 3 HTTP attempts.
* Payload: schema 2.0 — connection id, repository name/id, PR number, action, label, head/base SHA and refs, sender
  (untrusted), run id/attempt, delivery id, timestamp. No title, body, files or credentials.
* Signature: `X-PRQA-Signature: sha256=HMAC-SHA256(secret, "<X-PRQA-Timestamp>.<raw body>")`, ±300 s window,
  constant-time comparison, delivery-id replay protection, 16 KiB limit, repository bound to the connection.

## 5. Verification

1. Open a test PR in `{owner_repo}` and add the label `to be test`.
2. The "PRQA · to be test" job shows `PRQA dispatch accepted` (or `recorded, not executed` while PRQA is review-only).
3. Add an unrelated label: the job is skipped or reports "nothing dispatched".
4. `python3 scripts/setup/prqa_connect_repository.py status {owner_repo}` shows the connection as active.

## 6. Rollback

1. Delete `{WORKFLOW_PATH}` from the repository (or disable the workflow in the Actions tab).
2. `gh secret delete PRQA_WEBHOOK_SECRET --repo {owner_repo}`; `gh secret delete PRQA_WEBHOOK_URL --repo {owner_repo}`;
   `gh variable delete PRQA_CONNECTION_ID --repo {owner_repo}`.
3. `python3 scripts/setup/prqa_connect_repository.py revoke {owner_repo}` — the worker rejects the connection immediately
   (`401 CONNECTION_UNKNOWN`).
4. Rotate instead of revoking: `connect {owner_repo} --rotate-secret`, then export the new secret again.
"""


def update_env_file(path: Path, values: dict[str, str]) -> None:
    """Set non-secret KEY=VALUE lines in the private secrets.env without printing or disturbing other lines."""
    path = path.expanduser()
    lines = path.read_text(encoding="utf-8").splitlines() if path.exists() else []
    out, seen = [], set()
    for line in lines:
        key = line.split("=", 1)[0].strip()
        if key in values:
            out.append(f"{key}={values[key]}")
            seen.add(key)
        else:
            out.append(line)
    out += [f"{k}={v}" for k, v in values.items() if k not in seen]
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=".secrets.", dir=str(path.parent))
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write("\n".join(out) + "\n")
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def register_repository(registry_file: Path, repository: str) -> str:
    """Append a disabled, pending_approval real entry (never enables anything). Returns a status line."""
    import yaml
    data = yaml.safe_load(registry_file.read_text(encoding="utf-8")) or {}
    if any(r.get("full_name") == repository for r in data.get("repositories") or []):
        return "already present (unchanged)"
    if repository.startswith("synthetic-org/"):
        raise SetupError("synthetic-org/* names are reserved for fixtures")
    block = f"""
  # Added by scripts/setup/prqa_connect_repository.py: disabled until Phase-2 approval (enabled + approved + live mode).
  - full_name: {repository}
    kind: real
    enabled: false
    approval_status: pending_approval
    display_name: "{repository} (connected for `to be test`; pending approval)"
    default_branch: main
    allowed_events: [labeled]
    api:
      environment: staging
      base_url: "https://replace-me.staging.example.test"
      openapi_path: "/openapi.json"
      auth_profiles:
        anonymous: {{ type: none }}
    opencode:
      model: ""
    approved_by: null
    approved_at: null
"""
    text = registry_file.read_text(encoding="utf-8").rstrip("\n") + "\n" + block
    parsed = yaml.safe_load(text)
    if not any(r.get("full_name") == repository for r in parsed.get("repositories") or []):
        raise SetupError("registry entry could not be appended safely")
    registry_file.write_text(text, encoding="utf-8")
    return "added: disabled, pending_approval"


def write_package(out_dir: Path, repository: str, connection: conns.Connection, endpoint: dict, registered: str) -> Path:
    pkg = out_dir / repository.replace("/", "__")
    wf = pkg / WORKFLOW_PATH
    wf.parent.mkdir(parents=True, exist_ok=True)
    wf.write_text(render_workflow(repository, connection.connection_id), encoding="utf-8")
    (pkg / "INSTALL.md").write_text(render_install(repository, connection.connection_id, endpoint, registered), encoding="utf-8")
    meta = {"package_version": 1, "repository": repository, "connection_id": connection.connection_id, "label": connection.label,
            "workflow_path": WORKFLOW_PATH, "endpoint": endpoint, "registry_entry": registered,
            "github_secrets": ["PRQA_WEBHOOK_URL", "PRQA_WEBHOOK_SECRET"], "github_variables": {"PRQA_CONNECTION_ID": connection.connection_id},
            "secret_included": False}
    (pkg / "connection.json").write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return pkg


def cmd_connect(args) -> int:
    repository = args.repository.strip()
    if not conns.REPO_RE.match(repository):
        raise SetupError("repository must be OWNER/REPOSITORY (GitHub naming rules)")
    url = args.webhook_url if args.webhook_url is not None else os.environ.get("PRQA_PUBLIC_INGRESS_URL", "").strip() or None
    endpoint = endpoint_status(url, args.local_test)          # validate before anything is written
    store = conns.ConnectionStore(args.connections_dir)
    connection, action = store.connect(repository, rotate_secret=args.rotate_secret)
    if not args.no_env_update:
        update_env_file(Path(args.secrets_env), {"PRQA_ACTIONS_CONNECTIONS_DIR": str(store.directory),
                                                 "PRQA_ACTIONS_CONNECTIONS_GID": str(os.getgid())})
    registered = register_repository(Path(args.registry), repository) if args.register_repository else \
        "not changed (run with --register-repository, or add a disabled entry to config/repositories.yaml manually)"
    pkg = write_package(Path(args.out), repository, connection, endpoint, registered)
    print(json.dumps({"repository": repository, "connection_id": connection.connection_id, "connection": action,
                      "endpoint_status": endpoint["status"], "package": str(pkg), "registry_entry": registered,
                      "next": f"export-secret {repository} | gh secret set PRQA_WEBHOOK_SECRET --repo {repository}"}, indent=2))
    return 0


def cmd_export_secret(args) -> int:
    if sys.stdout.isatty():
        raise SetupError("refusing to print a secret to a terminal: pipe it, e.g. "
                         f"... export-secret {args.repository} | gh secret set PRQA_WEBHOOK_SECRET --repo {args.repository}")
    connection = conns.ConnectionStore(args.connections_dir).find_by_repository(args.repository.strip())
    if connection is None:
        raise SetupError("no active connection for this repository")
    sys.stdout.write(connection.secret)
    sys.stdout.flush()
    return 0


def cmd_revoke(args) -> int:
    cid = conns.ConnectionStore(args.connections_dir).revoke(args.repository.strip())
    print(json.dumps({"repository": args.repository, "revoked": cid}))
    return 0 if cid else 1


def cmd_status(args) -> int:
    connection = conns.ConnectionStore(args.connections_dir).find_by_repository(args.repository.strip())
    print(json.dumps(connection.public() if connection else {"repository": args.repository, "status": "not connected"}))
    return 0 if connection else 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--connections-dir", default=str(DEFAULT_CONNECTIONS_DIR.expanduser()))
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("connect")
    c.add_argument("repository")
    c.add_argument("--webhook-url", default=None, help="public https://HOST/webhook/prqa/actions (or env PRQA_PUBLIC_INGRESS_URL)")
    c.add_argument("--local-test", action="store_true", help="also allow http://127.0.0.1|localhost (offline tests only)")
    c.add_argument("--rotate-secret", action="store_true")
    c.add_argument("--register-repository", action="store_true", help="append a disabled, pending_approval registry entry")
    c.add_argument("--registry", default=str(REGISTRY_FILE))
    c.add_argument("--out", default=str(DEFAULT_OUT))
    c.add_argument("--secrets-env", default=str(DEFAULT_SECRETS_ENV.expanduser()))
    c.add_argument("--no-env-update", action="store_true")
    for name in ("export-secret", "revoke", "status"):
        p = sub.add_parser(name)
        p.add_argument("repository")
    args = ap.parse_args(argv)
    try:
        return {"connect": cmd_connect, "export-secret": cmd_export_secret, "revoke": cmd_revoke, "status": cmd_status}[args.cmd](args)
    except (SetupError, conns.ConnectionError_) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
